using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Diagnostics;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace PCL.Shion.SourceGenerators;

/// <summary>
/// 构建时把 <c>PCL_</c> 开头的环境变量写入 <c>PCL.Shion.Core.BuildSecrets</c> 的 <c>SecretDictionary</c>。
/// 只有设置了 <c>PCL_WRITE_SECRET</c> 时才写入，否则生成空字典。
/// </summary>
[Generator(LanguageNames.CSharp)]
public class BuildSecretsGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var secretProvider = context.CompilationProvider.Select(static (_, _) =>
        {
            // 判断 PCL_WRITE_SECRET 是否存在并遍历转换环境变量
            // 打死也不会用 MSBuild Properties 这种非人类设计出来的垃圾
#pragma warning disable RS1035
            var envs = Environment.GetEnvironmentVariables();
#pragma warning restore RS1035
            var secretPairs = envs.Contains("PCL_WRITE_SECRET") ? (
                from key in (
                    from key in envs.Keys.Cast<string>()
                    where !string.IsNullOrWhiteSpace(key) && key.StartsWith("PCL_") && key != "PCL_WRITE_SECRET"
                    select key
                )
                let value = envs[key]?.ToString()
                where !string.IsNullOrWhiteSpace(value)
                select (key.Substring(4), value)
            ) : [];
            return secretPairs;
        });

        // 只为 PCL.Shion.Core 生成，避免在其他引用了生成器的程序集中产生同名类型
        var isTarget = context.CompilationProvider.Select(static (compilation, _) =>
            compilation.AssemblyName == "PCL.Shion.Core");

        context.RegisterSourceOutput(secretProvider.Combine(isTarget), static (spc, pair) =>
        {
            if (pair.Right) _Execute(spc, pair.Left);
        });
    }

    private static void _Execute(SourceProductionContext context, IEnumerable<(string, string)> secretPairs)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// 此文件由 Source Generator 自动生成，请勿手动修改");
        sb.AppendLine();
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace PCL.Shion.Core;");
        sb.AppendLine();
        sb.AppendLine("partial class BuildSecrets");
        sb.AppendLine("{");
        sb.AppendLine("    private static readonly System.Collections.Generic.Dictionary<string, string?> SecretDictionary = new()");
        sb.AppendLine("    {");

        foreach (var (key, value) in secretPairs)
            sb.AppendLine($"        [\"{key}\"] = {_ToVerbatimString(value)},");

        sb.AppendLine("    };");
        sb.AppendLine("}");

        context.AddSource("BuildSecrets.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static string _ToVerbatimString(string text)
    {
        return "@\"" + text.Replace("\"", "\"\"") + "\"";
    }
}
